#!/usr/bin/env python3
"""
Lynceus Validation: CIC-IDS-2017 ML Benchmark (Sprint 1)
---------------------------------------------------------------------------
Research Objective:
Evaluate Lynceus (eBPF/XDP) against NTLFlowLyzer using the CIC-IDS-2017 dataset.

Methodology:
  1. Loads all labeled CSVs generated by cic_ids_2017_labeler.py
  2. Applies strict identity purge (Leakage Prevention).
  3. Applies LYN_P_NTL parity filter (187 features).
  4. Balances classes via Random Undersampling (RUS).
  5. Trains Random Forest (Multiclass or Binary).
"""

import os
import glob
import argparse
import pandas as pd
import numpy as np
from sklearn.ensemble import RandomForestClassifier
from sklearn.model_selection import train_test_split
from sklearn.metrics import classification_report, f1_score
from imblearn.under_sampling import RandomUnderSampler

# --- Configuration ---
BASE_DIR = "/opt/eBPFNetFlowLyzer"
PROCESSED_DIR = os.path.join(BASE_DIR, "data/processed/EBPF")

# Identity Purge
IDENTITY_DROP = [
    'flow_id', 'timestamp', 'src_ip', 'dst_ip', 'src_port', 'dst_port',
    'src_mac', 'dst_mac', 'protocol', 'ip_ver', 'eth_proto',
    'traffic_class', 'flow_label', 'TunnelId', 'TunnelType'
]



def load_and_merge_datasets(target_dir):
    csv_files = glob.glob(os.path.join(target_dir, "**", "labeled_*.csv"), recursive=True)
    if not csv_files:
        raise FileNotFoundError(f"No labeled CSVs found in {target_dir}")
        
    print(f"[*] Found {len(csv_files)} labeled CSV files.")
    df_list = []
    
    for f in csv_files:
        print(f"    -> Loading {os.path.basename(f)}...")
        df = pd.read_csv(f, low_memory=False)
        df_list.append(df)
        
    merged_df = pd.concat(df_list, ignore_index=True)
    return merged_df

def clean_dataset(df):
    """Drop identity columns, handle NaNs and infinities."""
    drop_cols = [c for c in IDENTITY_DROP if c in df.columns]
    df.drop(columns=drop_cols, inplace=True, errors='ignore')
    
    df.replace([np.inf, -np.inf], np.nan, inplace=True)
    df.fillna(0, inplace=True)
    return df

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--dir", type=str, default=PROCESSED_DIR, help="Directory containing labeled CSVs")
    parser.add_argument("--binary", action="store_true", help="Perform Binary (Attack vs Benign) classification")
    args = parser.parse_args()

    print("=== Lynceus CIC-IDS-2017 Validation (Sprint 1) ===")
    
    try:
        df = load_and_merge_datasets(args.dir)
    except FileNotFoundError as e:
        print(f"⚠️ {e}")
        return

    print(f"[*] Original Dataset Shape: {df.shape}")
    
    if args.binary:
        print("[*] Converting to Binary Classification...")
        df['Label'] = np.where(df['Label'] == 'BENIGN', 'BENIGN', 'ATTACK')

    print("[*] Utilizando a base de atributos completa do Lynceus (Full Mode)")
    
    print("[*] Purging Identity / Leakage Features...")
    df = clean_dataset(df)
    
    print(f"[*] Final Feature Shape: {df.shape}")
    print("[*] Class Distribution:")
    print(df['Label'].value_counts())

    X = df.drop(columns=['Label'])
    y = df['Label']

    # Free memory
    del df

    print("\n[*] Applying Random Undersampling (RUS)...")
    rus = RandomUnderSampler(random_state=42)
    X_res, y_res = rus.fit_resample(X, y)
    print(f"[*] Balanced Dataset Shape: {X_res.shape}")

    print("\n[*] Splitting Data (70/30)...")
    X_train, X_test, y_train, y_test = train_test_split(X_res, y_res, test_size=0.3, random_state=42, stratify=y_res)

    print("\n[*] Training Random Forest Classifier...")
    clf = RandomForestClassifier(n_estimators=50, n_jobs=-1, random_state=42)
    clf.fit(X_train, y_train)

    print("[*] Evaluating Model...")
    y_pred = clf.predict(X_test)
    
    print("\n" + "="*50)
    print("                 FINAL RESULTS")
    print("="*50)
    print(classification_report(y_test, y_pred, digits=4))
    
    f1_macro = f1_score(y_test, y_pred, average='macro')
    print(f"-> MACRO F1-SCORE: {f1_macro:.4f}")
    print("="*50)

if __name__ == "__main__":
    main()
